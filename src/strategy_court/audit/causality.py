"""Causality (look-ahead) test for black-box strategies.

Definition
----------
A strategy is causal if its weight process is *adapted* to the filtration generated by
prices: the weight decided at bar t is a function of prices[0..t] only. Equivalently, for
every t, the rows 0..t of signals() are invariant to any change of the data after t.

Test (dynamic, black-box; builds on the leakage framework of Kaufman et al. 2012)
-------------------------------------------------------------------------------
1. Determinism: signals(prices) must be reproducible, otherwise differences below are noise
   and the test is inconclusive rather than a false conviction.
2. Truncation: at K checkpoints t, run signals(prices[:t+1]); rows 0..t must equal the
   full-sample rows 0..t (all rows are compared, not only the last one).
3. Perturbation: keep the length but replace the future; rows 0..t must again be unchanged.
   Two complementary perturbations are used:
   * mirror: reflect the future log-price path around log p_t (p'_s = p_t^2 / p_s). Every
     future increment changes sign, so any direction-dependent leak is caught with certainty.
   * noise: multiply the future by an independent log-normal random walk with drift. Catches
     magnitude-only leaks (e.g. future volatility) that are invariant under the mirror.
   Perturbation catches leaks that survive truncation; truncation catches length-dependent
   code that perturbation cannot see.

A single violation proves look-ahead (it is a counterexample to adaptedness). The report
also gives a *lower bound* on the look-ahead depth: if removing data after t changes row r,
row r used data at least t - r + 1 bars ahead. "Global" scope (depth >= half the history at
the checkpoint) indicates full-sample statistics such as a scaler fitted on all data.

Note on economics vs detection: because the engine executes at t+1, a depth-1 peek is largely
absorbed by the fill lag (it earns ~nothing at next-close fills) yet it is still convicted —
look-ahead is a defect of the research process regardless of whether it happens to pay.

The honest re-run rebuilds the point-in-time weight path, row t = last row of
signals(prices[:t+1]) for every t, which is causal by construction, and backtests it.
"""

from collections.abc import Callable, Sequence
from dataclasses import dataclass, field
from typing import Literal

import numpy as np
import pandas as pd

from strategy_court.audit.citations import ARNOTT_HARVEY_MARKOWITZ_2019, KAUFMAN_2012
from strategy_court.backtest import (
    BacktestConfig,
    MarketData,
    PerformanceSummary,
    run_backtest,
    summarize,
)
from strategy_court.schemas import Evidence, Severity

SignalFn = Callable[[pd.DataFrame], pd.DataFrame]
Mode = Literal["truncate", "mirror", "noise"]
ALL_MODES: tuple[Mode, ...] = ("truncate", "mirror", "noise")
Status = Literal["pass", "fail", "inconclusive"]
TOOL = "causality"


@dataclass(frozen=True)
class CheckResult:
    t: int
    mode: Mode
    ok: bool
    error: str | None = None
    first_diff_row: int | None = None
    n_diff_cells: int = 0
    max_abs_diff: float = 0.0
    columns: tuple[str, ...] = ()

    @property
    def depth(self) -> int | None:
        return None if self.first_diff_row is None else self.t - self.first_diff_row + 1


@dataclass(frozen=True)
class CausalityReport:
    status: Status
    deterministic: bool
    n_bars: int
    checkpoints: tuple[int, ...]
    checks: tuple[CheckResult, ...] = field(default_factory=tuple)
    reason: str = ""

    @property
    def failures(self) -> list[CheckResult]:
        return [c for c in self.checks if not c.ok and c.error is None]

    @property
    def errors(self) -> list[CheckResult]:
        return [c for c in self.checks if c.error is not None]

    @property
    def lookahead_depth(self) -> int | None:
        depths = [c.depth for c in self.failures if c.depth is not None]
        return max(depths) if depths else None

    @property
    def scope(self) -> Literal["none", "local", "global"]:
        if not self.failures:
            return "none"
        is_global = any(c.depth is not None and c.depth >= (c.t + 1) / 2 for c in self.failures)
        return "global" if is_global else "local"

    @property
    def leaking_columns(self) -> list[str]:
        return sorted({col for c in self.failures for col in c.columns})

    def modes_failed(self) -> list[str]:
        return sorted({c.mode for c in self.failures})

    def to_evidence(self, strategy_id: str, evidence_id: str | None = None) -> Evidence:
        n_valid = len(self.checks) - len(self.errors)
        rate = len(self.failures) / n_valid if n_valid else 0.0
        severity = {
            "fail": Severity.CRITICAL,
            "inconclusive": Severity.HIGH,
            "pass": Severity.INFO,
        }[self.status]
        if self.status == "fail":
            summary = (
                f"Look-ahead detected: {len(self.failures)} of {n_valid} checks changed past "
                f"signals when future data was altered ({self.scope} leak, depth >= "
                f"{self.lookahead_depth} bars)."
            )
        elif self.status == "inconclusive":
            summary = f"Causality could not be established: {self.reason}."
        else:
            summary = f"No look-ahead: all {n_valid} truncation/perturbation checks passed."
        examples = [
            {
                "t": c.t,
                "mode": c.mode,
                "first_diff_row": c.first_diff_row,
                "depth": c.depth,
                "n_diff_cells": c.n_diff_cells,
                "columns": list(c.columns[:5]),
            }
            for c in self.failures[:5]
        ]
        return Evidence(
            id=evidence_id or f"{TOOL}:{strategy_id}",
            tool=TOOL,
            strategy_id=strategy_id,
            statistic_name="violation_rate",
            statistic=rate,
            flag=self.status == "fail",
            severity=severity,
            summary=summary,
            details={
                "status": self.status,
                "deterministic": self.deterministic,
                "n_checks": len(self.checks),
                "n_failed": len(self.failures),
                "n_errors": len(self.errors),
                "modes_failed": self.modes_failed(),
                "lookahead_depth": self.lookahead_depth,
                "scope": self.scope,
                "leaking_columns": self.leaking_columns[:20],
                "checkpoints": list(self.checkpoints),
                "examples": examples,
                "reason": self.reason,
            },
            citations=[KAUFMAN_2012, ARNOTT_HARVEY_MARKOWITZ_2019],
        )


def _call(fn: SignalFn, prices: pd.DataFrame) -> tuple[np.ndarray | None, str | None]:
    """Run the strategy and enforce the output contract on this input."""
    try:
        out = fn(prices.copy())
    except Exception as exc:
        return None, f"{type(exc).__name__}: {exc}"[:300]
    if not isinstance(out, pd.DataFrame):
        return None, f"returned {type(out).__name__}, expected DataFrame"
    if not out.index.equals(prices.index) or not out.columns.equals(prices.columns):
        return None, "output index/columns do not match the input"
    try:
        values = out.to_numpy(dtype=np.float64)
    except (TypeError, ValueError) as exc:
        return None, f"non-numeric output: {exc}"[:300]
    if np.isinf(values).any():
        return None, "output contains +/-inf"
    return values, None


def _mismatch(a: np.ndarray, b: np.ndarray, rtol: float, atol: float) -> np.ndarray:
    """Cell-wise difference; NaN (= hold) vs a number is a real difference, NaN vs NaN is not."""
    nan_a, nan_b = np.isnan(a), np.isnan(b)
    both = ~nan_a & ~nan_b
    differ = np.zeros(a.shape, dtype=bool)
    differ[both] = ~np.isclose(a[both], b[both], rtol=rtol, atol=atol)
    return np.asarray(differ | (nan_a ^ nan_b))


def _compare(
    t: int,
    mode: Mode,
    got: np.ndarray,
    ref: np.ndarray,
    columns: Sequence[str],
    rtol: float,
    atol: float,
) -> CheckResult:
    diff = _mismatch(got, ref, rtol, atol)
    if not diff.any():
        return CheckResult(t, mode, ok=True)
    rows, cols = np.nonzero(diff)
    finite = ~np.isnan(got) & ~np.isnan(ref) & diff
    max_abs = float(np.abs(got[finite] - ref[finite]).max()) if finite.any() else float("inf")
    return CheckResult(
        t,
        mode,
        ok=False,
        first_diff_row=int(rows.min()),
        n_diff_cells=int(diff.sum()),
        max_abs_diff=max_abs,
        columns=tuple(columns[i] for i in sorted(set(cols.tolist()))),
    )


def _mirror_future(prices: pd.DataFrame, t: int) -> pd.DataFrame:
    """Reflect each asset's future log-price path around its last valid price at or before t.

    Assets not yet listed at t have no anchor; their future is reflected around their first
    valid price instead (still a change of every future increment). NaN mask is preserved."""
    values = prices.to_numpy(dtype=np.float64)
    out = values.copy()
    past = values[: t + 1]
    for i in range(values.shape[1]):
        seen = np.flatnonzero(~np.isnan(past[:, i]))
        if seen.size:
            anchor_row = int(seen[-1])
        else:
            later = np.flatnonzero(~np.isnan(values[:, i]))
            anchor_row = int(later[0])
        anchor = values[anchor_row, i]
        start = max(t + 1, anchor_row + 1)
        out[start:, i] = anchor**2 / values[start:, i]
    return pd.DataFrame(out, index=prices.index, columns=prices.columns)


def _noise_future(prices: pd.DataFrame, t: int, rng: np.random.Generator) -> pd.DataFrame:
    """Multiply prices after t by an independent log-normal random walk (NaN mask preserved)."""
    values = prices.to_numpy(dtype=np.float64)
    logret = np.diff(np.log(values), axis=0)
    vol = np.nanstd(logret, axis=0) if logret.size else np.zeros(values.shape[1])
    vol = np.where(np.isfinite(vol) & (vol > 0), vol, 0.01)
    future = values.shape[0] - t - 1
    shocks = rng.standard_normal((future, values.shape[1])) * vol
    out = values.copy()
    out[t + 1 :] *= np.exp(np.cumsum(shocks, axis=0) + 2 * vol)  # + drift so levels move too
    return pd.DataFrame(out, index=prices.index, columns=prices.columns)


def default_checkpoints(n_bars: int, n_checkpoints: int, min_history: int | None) -> list[int]:
    lo = min_history if min_history is not None else max(2, n_bars // 10)
    lo = min(max(lo, 1), n_bars - 2)
    grid = np.linspace(lo, n_bars - 2, num=max(1, n_checkpoints))
    return sorted(set(np.rint(grid).astype(int).tolist()))


def causality_test(
    signal_fn: SignalFn,
    prices: pd.DataFrame,
    n_checkpoints: int = 16,
    min_history: int | None = None,
    modes: Sequence[Mode] = ALL_MODES,
    rtol: float = 1e-8,
    atol: float = 1e-10,
    seed: int = 0,
) -> CausalityReport:
    if len(prices) < 4:
        raise ValueError("causality test needs at least 4 bars")
    n_bars = len(prices)
    checkpoints = tuple(default_checkpoints(n_bars, n_checkpoints, min_history))
    cols = [str(c) for c in prices.columns]

    ref, err = _call(signal_fn, prices)
    if ref is None:
        return CausalityReport(
            "inconclusive", False, n_bars, checkpoints, reason=f"strategy failed: {err}"
        )
    again, err = _call(signal_fn, prices)
    if again is None or _mismatch(again, ref, rtol, atol).any():
        return CausalityReport(
            "inconclusive",
            False,
            n_bars,
            checkpoints,
            reason="strategy is non-deterministic (two identical runs differ); seed it",
        )

    rng = np.random.default_rng(seed)
    checks: list[CheckResult] = []
    for t in checkpoints:
        for mode in modes:
            if mode == "truncate":
                data = prices.iloc[: t + 1]
            elif mode == "mirror":
                data = _mirror_future(prices, t)
            else:
                data = _noise_future(prices, t, rng)
            got, err = _call(signal_fn, data)
            if got is None:
                checks.append(CheckResult(t, mode, ok=False, error=err))
                continue
            checks.append(_compare(t, mode, got[: t + 1], ref[: t + 1], cols, rtol, atol))

    failed = any(not c.ok and c.error is None for c in checks)
    if failed:
        status: Status = "fail"
        reason = ""
    elif all(c.error is not None for c in checks):
        status, reason = "inconclusive", "strategy errored on every truncated/perturbed input"
    else:
        status, reason = "pass", ""
    return CausalityReport(status, True, n_bars, checkpoints, tuple(checks), reason)


def point_in_time_signals(signal_fn: SignalFn, prices: pd.DataFrame) -> tuple[pd.DataFrame, int]:
    """Causal-by-construction weights: row t = last row of signals(prices[:t+1]).

    Costs one strategy call per bar. Bars where the strategy fails become NaN (= hold) and
    are counted, never hidden."""
    out = np.full(prices.shape, np.nan)
    errors = 0
    for t in range(len(prices)):
        values, _ = _call(signal_fn, prices.iloc[: t + 1])
        if values is None:
            errors += 1
            continue
        out[t] = values[-1]
    return pd.DataFrame(out, index=prices.index, columns=prices.columns), errors


@dataclass(frozen=True)
class CausalRerun:
    as_submitted: PerformanceSummary
    point_in_time: PerformanceSummary
    pit_errors: int

    def as_dict(self) -> dict[str, float | int | bool]:
        return {
            "sharpe_as_submitted": self.as_submitted.sharpe,
            "sharpe_point_in_time": self.point_in_time.sharpe,
            "cagr_as_submitted": self.as_submitted.cagr,
            "cagr_point_in_time": self.point_in_time.cagr,
            "pit_errors": self.pit_errors,
        }


def causal_rerun(
    signal_fn: SignalFn, market: MarketData, config: BacktestConfig | None = None
) -> CausalRerun:
    """Backtest the strategy as submitted and its point-in-time (leak-free) version."""
    full = run_backtest(signal_fn(market.close.copy()), market, config)
    pit, errors = point_in_time_signals(signal_fn, market.close)
    return CausalRerun(summarize(full), summarize(run_backtest(pit, market, config)), errors)
